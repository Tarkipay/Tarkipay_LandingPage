'use strict';
const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const out=path.resolve(__dirname,'../../evidencias/despues');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1100},timezoneId:'America/Lima'});
 const p=await context.newPage(),errors=[],results=[];p.on('pageerror',e=>errors.push(e.message));
 await p.clock.setFixedTime(new Date('2026-11-25T15:00:00-05:00'));
 await p.goto(process.env.TARKIPAY_TEST_URL||'http://127.0.0.1:8771/');await p.waitForFunction(()=>!!window.TarkiPayDemo);
 const idle=()=>p.evaluate(()=>TarkiPayDemo.whenIdle());
 const click=async s=>{await p.locator(s).click();await idle();};
 const select=async(s,value)=>{await p.locator(s).selectOption(value);await idle();};
 await click('[data-tab="tab-ventas"]');
 await p.locator('#sale-expected-amount').fill('20');await select('#sale-select-aviso','TP-1041');
 await click('#form-vincular-venta button[type="submit"]');
 assert.match(await p.locator('#venta-comparison-result').innerText(),/no confirma un abono/);
 assert((await p.evaluate(()=>TarkiPayDemo.api.sales())).some(v=>v.linkedAvisoId==='TP-1041'));
 await p.locator('#sale-expected-amount').fill('31');await click('#btn-mark-sale-pending');
 assert((await p.evaluate(()=>TarkiPayDemo.api.sales())).some(v=>v.expectedAmount===31&&v.status.includes('Pendiente')));
 results.push({name:'Asociación y venta pendiente mediante formularios existentes',status:'PASS'});
 await p.locator('#req-amount').fill('31');await p.locator('#req-sale-ref').fill('Referencia de prueba visual');
 await click('#form-request-review button[type="submit"]');
 const request=(await p.evaluate(()=>TarkiPayDemo.api.requests())).find(r=>r.saleRef==='Referencia de prueba visual');assert(request);
 await click(`[data-resolve="${request.id}"]`);await select('#demo-identity','U-2');await click('[data-tab="tab-ventas"]');
 await click('[data-req-filter="resolved"]');assert.match(await p.locator('#requests-list-container').innerText(),/Referencia de prueba visual/);
 results.push({name:'Solicitud y constancia de revisión, consultada por colaborador',status:'PASS'});
 await select('#demo-identity','U-1');await click('[data-tab="tab-equipo"]');
 await p.locator('#invite-name').fill('Integrante de prueba visual');await select('#invite-history-scope','month');
 await click('#form-invite-member button[type="submit"]');const code=(await p.locator('#generated-code-value').innerText()).trim();assert.match(code,/^\d+$/);
 const users=await p.evaluate(()=>TarkiPayDemo.api.context().users);const members=await p.evaluate(()=>TarkiPayDemo.api.team());
 const unused=users.find(u=>!members.some(m=>m.userId===u.id&&m.active));assert(unused);
 await select('#demo-identity',unused.id);
 await p.locator('.demo-join summary').click();await p.locator('#join-code').fill(code);await click('#form-join button[type="submit"]');await click('#join-confirm');
 assert.match(await p.locator('#demo-own-permissions').innerText(),/Colaborador/);
 await select('#demo-identity','U-1');await click('[data-tab="tab-equipo"]');
 const member=(await p.evaluate(()=>TarkiPayDemo.api.team())).find(m=>m.userId===unused.id&&m.active);assert(member);
 await click(`[data-edit="${member.id}"]`);await select('#edit-scope','week');await click('#form-edit-member button[type="submit"]');
 assert.equal((await p.evaluate(()=>TarkiPayDemo.api.team())).find(m=>m.id===member.id).scope,'week');
 await click(`[data-revoke="${member.id}"]`);await click('#demo-confirm-accept');
 assert.equal((await p.evaluate(()=>TarkiPayDemo.api.team())).find(m=>m.id===member.id).active,false);
 results.push({name:'Invitación, aceptación, edición de permisos/turno y revocación mediante UI',status:'PASS'});
 await p.setViewportSize({width:390,height:844});await click('[data-tab="tab-avisos"]');await p.locator('.notice-filter-disclosure summary').click();
 await p.locator('#filter-amount').fill('20');await click('#form-filter-avisos button[type="submit"]');assert.equal(await p.locator('.aviso-item').count(),2);
 await click('#btn-clear-all-filters');assert.equal(await p.locator('.aviso-item').count(),4);
 await p.reload();await p.waitForFunction(()=>!!window.TarkiPayDemo);await idle();
 assert((await p.evaluate(()=>TarkiPayDemo.api.sales())).some(v=>v.expectedAmount===31));
 assert.equal((await p.evaluate(()=>TarkiPayDemo.api.team())).find(m=>m.id===member.id).active,false);
 results.push({name:'Filtros desplegables a 390×844 y recarga de operaciones/revocación',status:'PASS'});
 assert.equal(errors.length,0);
 fs.writeFileSync(path.join(out,'operaciones-premium.json'),JSON.stringify({passed:results.length,failed:0,errors,results},null,2));
 await browser.close();console.log(JSON.stringify({passed:results.length,failed:0,errors}));
})().catch(e=>{console.error(e);process.exit(1);});
